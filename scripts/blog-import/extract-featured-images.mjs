// Extracts featured-image URLs from the WXR export and emits a SQL
// migration (017) that UPDATEs blog_posts.image_url for the ~10 posts
// whose original WordPress entry had a _thumbnail_id set.
// Run: node scripts/blog-import/extract-featured-images.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const inputPath = resolve('post.xml');
const outputPath = resolve('supabase/migrations/017_blog_featured_images.sql');

const xml = readFileSync(inputPath, 'utf8');
const chunks = xml.split('</item>').slice(0, -1).map((c) => c.split('<item>')[1]).filter(Boolean);

const cdata = (chunk, tag) => {
  const m = chunk.match(new RegExp(`<${tag}>\\s*<!\\[CDATA\\[([\\s\\S]*?)\\]\\]>\\s*</${tag}>`));
  return m ? m[1] : null;
};

const plainTag = (chunk, tag) => {
  const m = chunk.match(new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`));
  return m ? m[1] : null;
};

// Build attachment_id -> url lookup.
const attachmentUrls = new Map();
for (const chunk of chunks) {
  if (cdata(chunk, 'wp:post_type') !== 'attachment') continue;
  const id = parseInt(plainTag(chunk, 'wp:post_id') || '0', 10);
  const url = cdata(chunk, 'wp:attachment_url');
  if (id && url) attachmentUrls.set(id, url);
}

// Walk posts and pick each one's _thumbnail_id postmeta.
const updates = [];
for (const chunk of chunks) {
  if (cdata(chunk, 'wp:post_type') !== 'post') continue;
  if (cdata(chunk, 'wp:status') !== 'publish') continue;

  const postId = parseInt(plainTag(chunk, 'wp:post_id') || '0', 10);
  // postmeta blocks are ordered <wp:meta_key> then <wp:meta_value>.
  const metas = [...chunk.matchAll(/<wp:postmeta>[\s\S]*?<wp:meta_key><!\[CDATA\[([^\]]+)\]\]><\/wp:meta_key>[\s\S]*?<wp:meta_value><!\[CDATA\[([\s\S]*?)\]\]><\/wp:meta_value>[\s\S]*?<\/wp:postmeta>/g)];
  const thumbnailMeta = metas.find((m) => m[1] === '_thumbnail_id');
  if (!thumbnailMeta) continue;

  const thumbId = parseInt(thumbnailMeta[2], 10);
  const url = attachmentUrls.get(thumbId);
  if (!url) continue;

  updates.push({ postId, url });
}

if (!updates.length) {
  console.log('No featured images found in WXR.');
  process.exit(0);
}

const esc = (s) => `'${String(s).replace(/'/g, "''")}'`;

const sql = `-- ============================================================
-- Backfill blog_posts.image_url from the WordPress WXR's
-- _thumbnail_id / attachment mapping. Generated by
-- scripts/blog-import/extract-featured-images.mjs — do not edit by hand.
--
-- URLs still point at kingdavid4u.co.il/wp-content/uploads; good enough
-- while the legacy site is up. Migrate to Supabase Storage in a follow-up.
-- ============================================================
BEGIN;

${updates
  .map((u) => `UPDATE public.blog_posts SET image_url = ${esc(u.url)} WHERE source_post_id = ${u.postId};`)
  .join('\n')}

COMMIT;
`;

writeFileSync(outputPath, sql);

console.log(`Wrote ${outputPath} with ${updates.length} UPDATE statements.`);
for (const u of updates) {
  console.log(`  ${u.postId} -> ${u.url}`);
}
