-- The website uses the anon (public) key. Make sure the following
-- policies exist in kcrm so the website can read products and
-- write orders without authentication:
--
--   alter table public.products           enable row level security;
--   alter table public.product_variations enable row level security;
--   alter table public.orders             enable row level security;
--
--   create policy "products_public_read"
--     on public.products for select using (is_active = true);
--
--   create policy "variations_public_read"
--     on public.product_variations for select using (is_active = true);
--
--   create policy "orders_website_insert"
--     on public.orders for insert with check (source = 'website');
