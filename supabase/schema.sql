-- ============================================================
-- kcrm Supabase schema — REFERENCE ONLY
-- ============================================================
-- The CRM is the source of truth for these tables. The website (this repo)
-- READS from `products` + `product_variations` and INSERTS into `orders`.
--
-- Do NOT run this file against the kcrm DB — the tables already exist.
-- This document records the exact schema the website wrapper expects.
-- The actual table definitions live in the CRM project / its migrations.
--
-- If the CRM schema changes, update src/api/base44Client.js (transformProduct
-- + ENTITY_MAP) and src/pages/Checkout.jsx (orderRow shape) accordingly.
-- ============================================================

-- products
--   id                    uuid
--   created_date          timestamptz
--   updated_date          timestamptz
--   name                  text
--   description           text
--   sku                   text
--   is_active             boolean
--   default_variation_id  uuid -> product_variations(id)
--   bed_type              text
--   image_url             text
--   base_cost             numeric
--   warranty_years        int
--   features              text       -- newline / comma separated
--   has_trial_period      boolean
--   manager_notes         text
--   category              text
--   production_time_days  int
--   is_sample             boolean

-- product_variations
--   id            uuid
--   product_id    uuid -> products(id)
--   sku           text
--   name          text       -- e.g. "180x200"
--   base_price    numeric    -- list price
--   final_price   numeric    -- price actually charged (handles discounts)
--   width_cm      numeric
--   length_cm     numeric
--   is_active     boolean

-- orders (website inserts into this table)
--   id                  uuid
--   order_number        text     -- generated by site, e.g. "KD-XXXXX-YYY"
--   source              text     -- the website always sets "website"
--   customer_name       text
--   customer_phone      text
--   customer_email      text
--   delivery_address    text     -- "<street>, <apartment>"
--   delivery_city       text
--   apartment_number    text
--   items               jsonb    -- [{ product_id, variation_id, sku, name,
--                                --    size, quantity, with_storage,
--                                --    unit_price, line_total, image_url }]
--   extras              jsonb    -- { shipping, with_assembly, assembly,
--                                --   payment_method, website_notes }
--   subtotal            numeric
--   discount_total      numeric (0 from website)
--   vat_amount          numeric (0 from website)
--   total               numeric
--   payment_status      text     -- "pending"
--   production_status   text     -- "new"
--   delivery_status     text     -- "pending"
--   notes_sales         text

-- extra_charges (shipping rules — website reads, CRM dashboard owns)
--   id              uuid
--   created_date    timestamptz
--   name            text       -- human label shown in the CRM
--   description     text
--   cost            numeric    -- shipping price in ILS
--   is_active       bool
--   min_mattresses  int   default 0  -- inclusive lower bound on cart mattresses
--   max_mattresses  int               -- NULL = no upper bound
--   min_beds        int   default 0
--   max_beds        int               -- NULL = no upper bound
--   priority        int   default 0  -- tie-breaker; higher wins
--
-- The website fetches active rows on cart load and picks the rule
-- whose [min_*, max_*] ranges include the current cart's mattress
-- and bed counts. See supabase/migrations/018_extra_charges_rules.sql
-- for the column add + RLS policy.

-- ============================================================
-- RLS — required policies on the kcrm side for the website anon key
-- ============================================================
-- The website uses the anon (public) key. Make sure the following
-- policies exist in kcrm so the website can read products and
-- write orders without authentication:
--
--   alter table public.products           enable row level security;
--   alter table public.product_variations enable row level security;
--   alter table public.orders             enable row level security;
--
--   create policy "products_public_read"
--     on public.products for select using (is_active = true);
--
--   create policy "variations_public_read"
--     on public.product_variations for select using (is_active = true);
--
--   create policy "orders_website_insert"
--     on public.orders for insert with check (source = 'website');
--
