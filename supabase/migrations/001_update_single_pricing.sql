-- Strategy 1: match by SKU with -S suffix (single convention)
UPDATE public.product_variations v
SET base_price = n.price,
    final_price = n.price,
    updated_date = NOW()
FROM _new_prices n
WHERE v.sku = n.sheet_sku || '-S';

-- Strategy 2: match by plain SKU (no suffix)
UPDATE public.product_variations v
SET base_price = n.price,
    final_price = n.price,
    updated_date = NOW()
FROM _new_prices n
WHERE v.sku = n.sheet_sku
  AND (v.base_price IS NULL OR v.base_price = 0);

-- Strategy 3: match by product name + variation size (fallback)
UPDATE public.product_variations v
SET base_price = n.price,
    final_price = n.price,
    updated_date = NOW()
FROM _new_prices n, public.products p
WHERE v.product_id = p.id
  AND (v.base_price IS NULL OR v.base_price = 0)
  AND p.name ILIKE '%' || n.product_name || '%'
  AND (
    v.name = n.size_str
    OR REPLACE(v.name, 'x', '/') = n.size_str
    OR REPLACE(v.name, 'X', '/') = n.size_str
    OR REPLACE(v.name, '×', '/') = n.size_str
    OR (
      v.width_cm  = NULLIF(SPLIT_PART(n.size_str, '/', 1), '')::numeric
      AND v.length_cm = NULLIF(SPLIT_PART(n.size_str, '/', 2), '')::numeric
    )
  );

-- Summary: how many from the sheet did we actually apply?
WITH matched AS (
  SELECT n.sheet_sku, n.product_name, n.size_str, n.price,
         (SELECT v.sku FROM public.product_variations v
          WHERE v.sku = n.sheet_sku || '-S' OR v.sku = n.sheet_sku
          LIMIT 1) AS matched_sku
  FROM _new_prices n
)
SELECT
  (SELECT COUNT(*) FROM matched WHERE matched_sku IS NOT NULL) AS rows_matched_by_sku,
  (SELECT COUNT(*) FROM matched WHERE matched_sku IS NULL)     AS rows_not_matched_by_sku,
  (SELECT COUNT(*) FROM public.product_variations
   WHERE base_price IS NULL OR base_price = 0)                 AS variations_still_at_zero,
  (SELECT COUNT(*) FROM public.product_variations
   WHERE base_price > 0)                                       AS variations_priced;

-- List sheet rows that did NOT match any CRM variation (so you can fix them)
SELECT n.sheet_sku, n.product_name, n.size_str, n.price
FROM _new_prices n
WHERE NOT EXISTS (
  SELECT 1 FROM public.product_variations v
  WHERE v.sku = n.sheet_sku || '-S' OR v.sku = n.sheet_sku
)
ORDER BY n.sheet_sku;

